export function SocialIcon({ platform, size = 18, className = '', ...props }) {
  const norm = String(platform || '').toLowerCase().trim();
  if (norm.includes('whatsapp')) return <WhatsAppIcon size={size} className={className} {...props} />;
  if (norm.includes('telegram')) return <TelegramIcon size={size} className={className} {...props} />;
  if (norm.includes('youtube')) return <YouTubeIcon size={size} className={className} {...props} />;
  if (norm.includes('linkedin')) return <LinkedInIcon size={size} className={className} {...props} />;
  if (norm.includes('facebook')) return <FacebookIcon size={size} className={className} {...props} />;
  if (norm.includes('instagram')) return <InstagramIcon size={size} className={className} {...props} />;
  if (norm === 'x' || norm.includes('twitter')) return <XIcon size={size} className={className} {...props} />;
  if (norm.includes('snapchat')) return <SnapchatIcon size={size} className={className} {...props} />;
  return null;
}
